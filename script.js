function initReviewsCarousel() {
    const carousel = document.querySelector("[data-review-carousel]");
    const track = document.querySelector("[data-review-track]");
    const prev = document.querySelector("[data-review-prev]");
    const next = document.querySelector("[data-review-next]");
    if (!carousel || !track) return;

    const cards = Array.from(track.querySelectorAll(".review-card"));
    if (!cards.length) return;

    let index = 0;
    let timer = null;
    const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

    const cardStep = () => {
        const first = cards[0].getBoundingClientRect();
        const gap = Number.parseFloat(getComputedStyle(track).columnGap || "0");
        return first.width + gap;
    };

    const goTo = (nextIndex) => {
        index = (nextIndex + cards.length) % cards.length;
        carousel.scrollTo({
            left: index * cardStep(),
            behavior: reduceMotion ? "auto" : "smooth"
        });
    };

    const start = () => {
        if (reduceMotion || timer) return;
        timer = window.setInterval(() => goTo(index + 1), 5200);
    };

    const stop = () => {
        if (!timer) return;
        window.clearInterval(timer);
        timer = null;
    };

    prev?.addEventListener("click", () => {
        stop();
        goTo(index - 1);
        start();
    });

    next?.addEventListener("click", () => {
        stop();
        goTo(index + 1);
        start();
    });

    carousel.addEventListener("pointerenter", stop);
    carousel.addEventListener("pointerleave", start);
    carousel.addEventListener("focusin", stop);
    carousel.addEventListener("focusout", start);
    window.addEventListener("resize", () => goTo(index), { passive: true });

    start();
}

function initSmoothScroll() {
    const links = document.querySelectorAll('a[href^="#"]');
    const navLinks = document.querySelectorAll(".nav-link");
    const sections = document.querySelectorAll("main section[id]");

    links.forEach((link) => {
        link.addEventListener("click", (event) => {
            const selector = link.getAttribute("href");
            if (!selector || selector === "#") return;
            const target = document.querySelector(selector);
            if (!target) return;
            event.preventDefault();
            window.scrollTo({
                top: target.offsetTop - 72,
                behavior: "smooth"
            });
        });
    });

    const updateActiveLink = () => {
        let current = "home";
        sections.forEach((section) => {
            if (window.scrollY >= section.offsetTop - 140) current = section.id;
        });
        navLinks.forEach((link) => {
            link.classList.toggle("active", link.getAttribute("href") === `#${current}`);
        });
    };

    updateActiveLink();
    window.addEventListener("scroll", updateActiveLink, { passive: true });
}
